"""Markdown + CSV output for the paper."""

from __future__ import annotations

import csv
import io
from collections import Counter

from research.redteam.result import Result

COLUMNS = ["id", "group", "threat", "goal", "regime", "attack", "entry",
           "expected_layer", "expected_status",
           "observed_layer", "observed_status", "matches_expected", "llm_layer",
           "residual", "fixed_by", "evidence", "location", "notes"]

GROUP_TITLES = {
    "S": "Strategy write path (self-modification)",
    "O": "Order gates",
    "D": "Dispatch and regime (oversight switches)",
    "X": "Prompt injection via external content",
    "M": "Memory and context integrity",
    "H": "Human-oversight integrity",
    "L": "Least privilege (tool-use isolation)",
    "A": "Visibility of lost oversight (T6 checks)",
}


def _matches(r: Result, meta: dict) -> str:
    return ("yes" if r.status == meta["expected_status"]
            and r.layer == meta["expected_layer"] else "no")


def rows(results: list[Result], meta: dict[str, dict]) -> list[dict]:
    out = []
    for r in results:
        m = meta[r.id]
        out.append({
            "id": r.id, "group": m["group"], "threat": m.get("threat", ""),
            "goal": m.get("goal", ""), "regime": m.get("regime", ""),
            "attack": m["attack"],
            "entry": m["entry"], "expected_layer": m["expected_layer"],
            "expected_status": m["expected_status"], "observed_layer": r.layer,
            "observed_status": r.status, "matches_expected": _matches(r, m),
            "llm_layer": m["llm_layer"], "residual": m.get("residual", ""),
            "fixed_by": m.get("fixed_by", ""),
            "evidence": r.evidence,
            "location": r.location, "notes": r.notes})
    return out


def to_csv(results: list[Result], meta: dict[str, dict]) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=COLUMNS, lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows(results, meta))
    return buf.getvalue()


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


STATUS_ORDER = ("caught", "neutralised", "bounded", "not caught", "error")


def _threat_summary(table: list[dict]) -> list[str]:
    """Rows per threat by observed status. A row tagged with two threats
    counts under both, so the columns can sum to more than the case count."""
    by: dict[str, Counter] = {}
    ids: dict[str, list[str]] = {}
    for r in table:
        for t in filter(None, (x.strip() for x in r["threat"].split(","))):
            by.setdefault(t, Counter())[r["observed_status"]] += 1
            ids.setdefault(t, []).append(r["id"])
    if not by:
        return []
    lines = ["## By threat", "",
             "| Threat | Rows | " + " | ".join(STATUS_ORDER[:4]) + " | Not caught / bounded |",
             "|---|---|---|---|---|---|---|"]
    for t in sorted(by, key=lambda x: int(x[1:]) if x[1:].isdigit() else 99):
        c = by[t]
        residual = [i for i in ids[t]
                    if next(r for r in table if r["id"] == i)["observed_status"]
                    in ("not caught", "bounded")]
        lines.append(f"| {t} | {sum(c.values())} | "
                     + " | ".join(str(c.get(k, 0)) for k in STATUS_ORDER[:4])
                     + f" | {', '.join(residual) or '-'} |")
    return [*lines, "", "## All rows", ""]


def to_markdown(results: list[Result], meta: dict[str, dict]) -> str:
    table = rows(results, meta)
    counts = Counter(r["observed_status"] for r in table)
    lines = [
        "# R1 gate red-team results",
        "",
        ("Generated by `uv run python -m research.redteam` (offline; temp DB; "
         "production assembly with fake broker, market data, LLM and web "
         "search). Do not edit by hand."),
        "",
        (f"Cases: {len(table)}. " + ", ".join(
            f"{k}: {counts[k]}" for k in
            ("caught", "neutralised", "bounded", "not caught", "error")
            if counts.get(k)) + ". "
         f"Matched the pre-run prediction: "
         f"{sum(r['matches_expected'] == 'yes' for r in table)}/{len(table)}."),
        "",
        ("`LLM layer: scripted` rows feed a scripted model output through the "
         "real code; they show what the code does with a hostile output, not "
         "whether a real model would produce it."),
        "",
        *_threat_summary(table),
        ("| ID | Threat | Goal | Regime | Attack | Expected | Observed | Match | LLM "
         "| Residual | Evidence | Location |"),
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    group = None
    for r in table:
        if r["group"] != group:
            group = r["group"]
            lines.append(f"| **{group}** | | | | **{GROUP_TITLES.get(group, group)}** "
                         "| | | | | | | |")
        lines.append(
            f"| {r['id']} | {r['threat']} | {r['goal']} | {r['regime']} "
            f"| {_cell(r['attack'])} "
            f"| {r['expected_status']} ({r['expected_layer']}) "
            f"| {r['observed_status']} ({r['observed_layer']}) "
            f"| {r['matches_expected']} | {r['llm_layer']} | {r['residual']} "
            f"| {_cell(r['evidence'])} | {_cell(r['location'])} |")
    notes = [r for r in table if r["notes"]]
    if notes:
        lines += ["", "## Notes", ""]
        lines += [f"- **{r['id']}**: {_cell(r['notes'])}" for r in notes]
    return "\n".join(lines) + "\n"


def before_after(baseline: list[dict], results: list[Result], meta: dict[str, dict],
                 *, before_label: str, after_label: str) -> str:
    """Markdown comparing a baseline results CSV (rows as dicts) with a new
    run: totals, every row whose status or layer changed, new rows, and the
    rows still getting through."""
    after = {r["id"]: r for r in rows(results, meta)}
    before = {r["id"]: r for r in baseline}

    def totals(rs) -> str:
        c = Counter(r["observed_status"] for r in rs)
        return " / ".join(str(c.get(k, 0)) for k in STATUS_ORDER[:4])

    common = [i for i in after if i in before]
    changed = [i for i in common
               if (before[i]["observed_status"], before[i]["observed_layer"])
               != (after[i]["observed_status"], after[i]["observed_layer"])]
    added = [i for i in after if i not in before]
    removed = [i for i in before if i not in after]
    through = [i for i in after if after[i]["observed_status"] in ("not caught", "bounded")]

    def cell(r) -> str:
        return f"{r['observed_status']} ({r['observed_layer']})"

    lines = [
        f"# R1 before/after: {before_label} vs {after_label}",
        "",
        "Totals are caught / neutralised / bounded / not caught.",
        "",
        "| Run | Cases | Totals |",
        "|---|---|---|",
        f"| {before_label} | {len(before)} | {totals(before.values())} |",
        f"| {after_label} | {len(after)} | {totals(after.values())} |",
        (f"| {after_label}, rows also in {before_label} | {len(common)} | "
         f"{totals(after[i] for i in common)} |"),
        "",
        f"## Rows that changed ({len(changed)})",
        "",
        "| ID | Threat | Before | After | Fixed by | After evidence |",
        "|---|---|---|---|---|---|",
    ]
    lines += [f"| {i} | {after[i]['threat']} | {cell(before[i])} | {cell(after[i])} "
              f"| {after[i]['fixed_by'] or '-'} | {_cell(after[i]['evidence'])} |"
              for i in changed]
    lines += ["", f"## New rows ({len(added)})", "",
              "| ID | Threat | Attack | Result | Fixed by |", "|---|---|---|---|---|"]
    lines += [f"| {i} | {after[i]['threat']} | {_cell(after[i]['attack'])} | {cell(after[i])} "
              f"| {after[i]['fixed_by'] or '-'} |" for i in added]
    if removed:
        lines += ["", f"Rows only in {before_label}: {', '.join(removed)}."]
    lines += ["", f"## Still not caught or bounded in {after_label} ({len(through)})", "",
              "| ID | Threat | Result | Residual |", "|---|---|---|---|"]
    lines += [f"| {i} | {after[i]['threat']} | {cell(after[i])} | {after[i]['residual'] or '-'} |"
              for i in through]
    return "\n".join(lines) + "\n"
